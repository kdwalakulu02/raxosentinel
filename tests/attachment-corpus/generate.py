"""Builds the Phase 3D attachment regression corpus: ZIP (ordinary, nested, multiple,
polyglot, malformed, encrypted, bombs), Office Open XML and legacy Office documents,
TAR/GZIP/BZIP2/XZ, unsupported formats and YARA-X marker fixtures.

The only "malware" is the EICAR anti-virus test string; YARA fixtures carry synthetic
markers matched by tests/yara-rules/valid. Each MANIFEST.tsv row records the verdict
expected without YARA-X rules and with `--yara-rules tests/yara-rules/valid`.

Office documents come from LibreOffice and encrypted ZIPs from Info-ZIP; those tools
embed timestamps/random salts, so regenerated bytes differ. The committed fixtures are
pinned by SHA-256 in MANIFEST.tsv.
"""
