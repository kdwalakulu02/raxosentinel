def add(name, data, expected, category, structure, expected_yara=None, notes=""):
    (OUT / name).write_bytes(data)
    ROWS.append((name, expected, expected_yara or expected, category, structure,
                 hashlib.sha256(data).hexdigest(), str(len(data)), notes))


def zip_bytes(entries, comment=b""):
    """entries: (name, data, method) with fixed timestamps."""
    buf = io.BytesIO()
    with zipfile.ZipFile(buf, "w") as z:
        for name, data, method in entries:
            info = zipfile.ZipInfo(name, DATE)
            info.compress_type = method
            info.external_attr = 0o644 << 16
            z.writestr(info, data)
        z.comment = comment
    return buf.getvalue()


S, D = zipfile.ZIP_STORED, zipfile.ZIP_DEFLATED


def local_record(name, data):
    return struct.pack("<4sHHHHHIIIHH", b"PK\x03\x04", 20, 0, 0, 0, 0x21, zlib.crc32(data),
                       len(data), len(data), len(name), 0) + name + data


def central_entry(name, data, offset):
    return struct.pack("<4sHHHHHHIIIHHHHHII", b"PK\x01\x02", 20, 20, 0, 0, 0, 0x21,
                       zlib.crc32(data), len(data), len(data), len(name), 0, 0, 0, 0, 0,
                       offset) + name


def eocd(count, cd_size, cd_offset):
    return struct.pack("<4sHHHHIIH", b"PK\x05\x06", 0, 0, count, count, cd_size, cd_offset, 0)


def tar_bytes(entries, fmt=tarfile.GNU_FORMAT):
    buf = io.BytesIO()
    with tarfile.open(fileobj=buf, mode="w", format=fmt) as t:
        for name, data in entries:
            info = tarfile.TarInfo(name)
            info.size = len(data)
            info.mtime = 1798761600
            info.uname = info.gname = "raxo"
            t.addfile(info, io.BytesIO(data))
    return buf.getvalue()


def gz(data):
    return gzip.compress(data, compresslevel=9, mtime=0)


def minimal_pdf(stream_payload=None):
    objs = [b"<< /Type /Catalog /Pages 2 0 R >>",
            b"<< /Type /Pages /Kids [3 0 R] /Count 1 >>",
            b"<< /Type /Page /Parent 2 0 R /MediaBox [0 0 200 200] /Contents 4 0 R >>"]
    content = stream_payload if stream_payload is not None else b"BT /F1 12 Tf 20 100 Td (Hello) Tj ET"
    comp = zlib.compress(content, 9)
    objs.append(b"<< /Length " + str(len(comp)).encode() + b" /Filter /FlateDecode >>\nstream\n"
                + comp + b"\nendstream")
    out = bytearray(b"%PDF-1.7\n%\xe2\xe3\xcf\xd3\n")
    offsets = []
    for i, body in enumerate(objs, start=1):
        offsets.append(len(out))
        out += f"{i} 0 obj\n".encode() + body + b"\nendobj\n"
    xref = len(out)
    out += f"xref\n0 {len(objs) + 1}\n0000000000 65535 f \n".encode()
    for off in offsets:
        out += f"{off:010} 00000 n \n".encode()
    out += f"trailer\n<< /Size {len(objs) + 1} /Root 1 0 R >>\nstartxref\n{xref}\n%%EOF\n".encode()
    return bytes(out)


def text_lines(n_bytes, seed):
    rnd = random.Random(seed)
    words = [b"invoice", b"ledger", b"account", b"quarter", b"payment", b"supplier", b"total"]
    out = bytearray()
    i = 0
    while len(out) < n_bytes:
        out += b"%d %s %s %d.%02d\n" % (i, rnd.choice(words), rnd.choice(words),
                                         rnd.randrange(100000), rnd.randrange(100))
        i += 1
    return bytes(out[:n_bytes])


def repetitive(n_bytes, seed):
    """Large but modestly compressible text (~80:1 deflate, below the 1000:1 bomb ratio)."""
    block = text_lines(20_000, seed)
    return (block * (n_bytes // len(block) + 1))[:n_bytes]


def soffice(src, fmt, extra=()):
    profile = f"-env:UserInstallation=file://{TMP}/lo-profile"
    subprocess.run(["soffice", profile, "--headless", *extra, "--convert-to", fmt, "--outdir",
                    str(TMP), str(src)], check=True, stdout=subprocess.DEVNULL,
                   stderr=subprocess.DEVNULL)


def with_members(package, extra):
    """Copies an OOXML package and appends extra members."""
    src = zipfile.ZipFile(io.BytesIO(package))
    buf = io.BytesIO()
    with zipfile.ZipFile(buf, "w") as z:
        for info in src.infolist():
            z.writestr(info, src.read(info.filename))
        for name, data in extra:
            info = zipfile.ZipInfo(name, DATE)
            info.compress_type = D
            z.writestr(info, data)
    return buf.getvalue()


