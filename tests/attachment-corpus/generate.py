def main():
    if OUT.exists():
        shutil.rmtree(OUT)
    OUT.mkdir(parents=True)
    zips()
    compressed()
    unsupported()
    office()
    yara()
    with open(HERE / "MANIFEST.tsv", "w", encoding="utf-8") as f:
        f.write("# file\texpected\texpected_with_yara\tcategory\tstructure\tsha256\tbytes\tnotes\n")
        for row in sorted(ROWS):
            f.write("\t".join(row) + "\n")
    shutil.rmtree(TMP, ignore_errors=True)
    print(f"{len(ROWS)} fixtures written to {OUT}")


if __name__ == "__main__":
    sys.exit(main())
