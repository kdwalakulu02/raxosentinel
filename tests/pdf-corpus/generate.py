def mupdf_incremental():
    ver = "MuPDF " + tool_version(["mutool", "-v"])
    script = TMP / "incr.js"

    def incremental(src, dst, body):
        script.write_text(
            "var doc = Document.openDocument(scriptArgs[0]).asPDF();\n" + body +
            "\ndoc.save(scriptArgs[1], 'incremental');\n", encoding="utf-8")
        shutil.copy(src, dst)
        run("mutool", "run", str(script), str(dst), str(dst))

    add_info = "var info = doc.getTrailer().get('Info'); info.put('Subject', 'Revised by incremental update');"
    incremental(OUT / "reportlab-compressed.pdf", OUT / "mupdf-incremental-clean.pdf", add_info)
    add("mupdf-incremental-clean.pdf", "CLEAN", ver, "incremental update appended to a classic file")
    incremental(OUT / "cairo-default.pdf", OUT / "mupdf-incremental-objstm.pdf", add_info)
    add("mupdf-incremental-objstm.pdf", "CLEAN", ver, "incremental update over object/xref streams")
    # EICAR attachment added in a later revision (Flate compressed stream).
    attach = (
        "var buf = new Buffer(); buf.writeLine('" + EICAR.decode().replace("\\", "\\\\") + "');\n"
        "var s = doc.addStream(buf, {Type: 'EmbeddedFile'});\n"
        "var fs = doc.addObject({Type: 'Filespec', F: 'eicar.com', UF: 'eicar.com', EF: {F: s}});\n"
        "doc.getTrailer().get('Root').put('Names', doc.newDictionary());\n"
        "doc.getTrailer().get('Root').get('Names').put('EmbeddedFiles', {Names: ['eicar.com', fs]});\n"
    )
    incremental(OUT / "reportlab-compressed.pdf", OUT / "eicar-incremental-added.pdf", attach)
    add("eicar-incremental-added.pdf", "DETECTED", ver, "EICAR attachment introduced in a later revision",
        category="detection")
    # EICAR present only in the original revision, removed by a later incremental update.
    removal = "doc.getTrailer().get('Root').delete('Names');"
    incremental(OUT / "eicar-attachment-classic.pdf", OUT / "eicar-incremental-shadowed.pdf", removal)
    add("eicar-incremental-shadowed.pdf", "DETECTED", ver,
        "EICAR attachment only in a superseded revision (still physically present)", category="detection")


def synthetic_structures():
    """Hand-built PDFs for features generators do not emit on demand."""

    def build(objects, trailer_extra=""):
        out = bytearray(b"%PDF-1.7\n%\xe2\xe3\xcf\xd3\n")
        offsets = []
        for num, body in enumerate(objects, start=1):
            offsets.append(len(out))
            out += f"{num} 0 obj\n".encode() + body + b"\nendobj\n"
        xref = len(out)
        out += f"xref\n0 {len(objects) + 1}\n0000000000 65535 f \n".encode()
        for off in offsets:
            out += f"{off:010} 00000 n \n".encode()
        out += (f"trailer\n<< /Size {len(objects) + 1} /Root 1 0 R {trailer_extra}>>\n"
                f"startxref\n{xref}\n%%EOF\n").encode()
        return bytes(out)

    def stream(data, extra=b""):
        return b"<< /Length " + str(len(data)).encode() + b" " + extra + b" >>\nstream\n" + data + b"\nendstream"

    catalog = b"<< /Type /Catalog /Pages 2 0 R /Names << /EmbeddedFiles << /Names [(a) 4 0 R] >> >> >>"
    pages = b"<< /Type /Pages /Kids [3 0 R] /Count 1 >>"
    page = b"<< /Type /Page /Parent 2 0 R /MediaBox [0 0 200 200] >>"
    filespec = b"<< /Type /Filespec /F (a.com) /EF << /F 5 0 R >> >>"

    def with_payload(stream_obj):
        return build([catalog, pages, page, filespec, stream_obj])

    gen = "generate.py (hand-built, PDF 32000-1 syntax)"
    text = " ".join(f"line {i} of the quarterly ledger" for i in range(400)).encode()
    text_flate = zlib.compress(text, 9)
    # BTYPE bits of the first deflate block header set to 11 (reserved).
    corrupt_flate = text_flate[:2] + bytes([text_flate[2] | 0x06]) + text_flate[3:]
    hexed = zlib.compress(EICAR).hex().encode() + b">"
    fixtures = [
        ("eicar-ahx-flate-chain.pdf", "DETECTED", "detection",
         stream(hexed, b"/Type /EmbeddedFile /Filter [/ASCIIHexDecode /FlateDecode]"),
         "EICAR behind an [/ASCIIHexDecode /FlateDecode] filter chain"),
        ("eicar-hex-string-info.pdf", None, "detection", None,
         "EICAR only as a hex string in the document Info dictionary"),
        ("malformed-corrupt-flate.pdf", "UNSCANNED", "malformed",
         stream(corrupt_flate, b"/Type /EmbeddedFile /Filter /FlateDecode"),
         "EmbeddedFile whose first deflate block uses the reserved block type 3"),
        ("malformed-truncated-flate.pdf", "UNSCANNED", "malformed",
         stream(text_flate[:len(text_flate) // 2], b"/Type /EmbeddedFile /Filter /FlateDecode"),
         "EmbeddedFile whose deflate data stops before the final block"),
        ("flate-trailing-garbage.pdf", "CLEAN", "tolerated",
         stream(zlib.compress(b"harmless " * 400)[:40] + b"\x00garbage\xff" * 8,
                b"/Type /EmbeddedFile /Filter /FlateDecode"),
         "complete deflate body, Adler-32 cut short, trailing bytes after the final block"),
        ("unsupported-unknown-filter.pdf", "UNSCANNED", "unsupported",
         stream(b"opaque", b"/Type /EmbeddedFile /Filter /RaxoUnknownDecode"),
         "stream with a filter no PDF reader implements"),
        ("bomb-flate-embedded.pdf", "ERROR", "resource",
         stream(zlib.compress(b"\0" * (64 * 1024 * 1024), 9), b"/Type /EmbeddedFile /Filter /FlateDecode"),
         "64 MiB of zeros compressed ~1000:1 in one EmbeddedFile"),
    ]
    for name, expected, category, obj, struct in fixtures:
        if name == "eicar-hex-string-info.pdf":
            data = build([catalog.replace(b" /Names << /EmbeddedFiles << /Names [(a) 4 0 R] >> >>", b""),
                          pages, page, b"<< /Title <" + EICAR.hex().encode() + b"> >>"], "/Info 4 0 R ")
            expected = "DETECTED"
        else:
            data = with_payload(obj)
        (OUT / name).write_bytes(data)
        add(name, expected, gen, struct, category=category)
    # Object-stream bomb: one object stream that inflates far beyond the load-time limit.
    body = b"1 0 " + b"[" + b"0 " * (40 * 1024 * 1024) + b"]"
    comp = zlib.compress(body, 9)
    objstm = (b"<< /Type /ObjStm /N 1 /First 4 /Filter /FlateDecode /Length " + str(len(comp)).encode()
              + b" >>\nstream\n" + comp + b"\nendstream")
    data = build([b"<< /Type /Catalog /Pages 2 0 R >>", pages, page, objstm])
    (OUT / "bomb-object-stream.pdf").write_bytes(data)
    add("bomb-object-stream.pdf", "ERROR", gen, "object stream inflating to 80 MiB",
        category="resource")


def malformed():
    src = (OUT / "libreoffice-docx-export.pdf").read_bytes()
    (OUT / "malformed-truncated.pdf").write_bytes(src[: len(src) * 6 // 10])
    add("malformed-truncated.pdf", "UNSCANNED", "truncation of libreoffice-docx-export.pdf",
        "file cut at 60%; xref and trailer missing", category="malformed")
    damaged = bytearray(src)
    pos = damaged.rfind(b"startxref")
    damaged[pos + 10: pos + 12] = b"99"
    (OUT / "malformed-bad-startxref.pdf").write_bytes(bytes(damaged))
    add("malformed-bad-startxref.pdf", "UNSCANNED", "byte edit of libreoffice-docx-export.pdf",
        "startxref offset corrupted", category="malformed")
    (OUT / "malformed-header-only.pdf").write_bytes(b"%PDF-1.7\n%\xe2\xe3\xcf\xd3\n")
    add("malformed-header-only.pdf", "UNSCANNED", "generate.py", "header without body", category="malformed")


def main():
    if OUT.exists():
        shutil.rmtree(OUT)
    OUT.mkdir(parents=True)
    os.environ.setdefault("SOURCE_DATE_EPOCH", "1798761600")
    make_images()
    libreoffice()
    chromium()
    cairo_fixtures()
    reportlab_fixtures()
    scanned()
    qpdf_fixtures()
    mupdf_incremental()
    synthetic_structures()
    malformed()
    with open(HERE / "MANIFEST.tsv", "w", encoding="utf-8") as f:
        f.write("# file\texpected\tcategory\tgenerator\tstructure\tsha256\tbytes\tnotes\n")
        for row in sorted(ROWS):
            f.write("\t".join(row) + "\n")
    shutil.rmtree(TMP, ignore_errors=True)
    print(f"{len(ROWS)} fixtures written to {OUT}")


if __name__ == "__main__":
    sys.exit(main())
