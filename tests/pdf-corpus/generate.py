def cairo_fixtures():
    import cairo

    ver = f"cairo {cairo.cairo_version_string()} (pycairo {cairo.version})"

    def draw(surface, pages=3, image=True):
        ctx = cairo.Context(surface)
        for page in range(pages):
            ctx.select_font_face("DejaVu Sans")
            ctx.set_font_size(14)
            for i, line in enumerate(PARAGRAPHS * 3):
                ctx.move_to(50, 60 + i * 22)
                ctx.show_text(f"{page + 1}.{i} {line}")
            ctx.set_source_rgb(0.2, 0.4, 0.8)
            ctx.rectangle(50, 400, 200 + page * 40, 120)
            ctx.fill()
            if image:
                img = cairo.ImageSurface.create_from_png(str(TMP / "chart.png"))
                ctx.save()
                ctx.translate(300, 450)
                ctx.scale(0.3, 0.3)
                ctx.set_source_surface(img)
                ctx.paint()
                ctx.restore()
            ctx.set_source_rgb(0, 0, 0)
            ctx.show_page()
        surface.finish()

    s = cairo.PDFSurface(str(OUT / "cairo-default.pdf"), 595, 842)
    s.set_metadata(cairo.PDFMetadata.TITLE, "Cairo default")
    draw(s)
    add("cairo-default.pdf", "CLEAN", ver, "PDF 1.7 object streams + xref stream; Flate images (cairo default)")
    s = cairo.PDFSurface(str(OUT / "cairo-pdf14.pdf"), 595, 842)
    s.restrict_to_version(cairo.PDFVersion.VERSION_1_4)
    draw(s)
    add("cairo-pdf14.pdf", "CLEAN", ver, "PDF 1.4 restricted; classic xref")
    s = cairo.PDFSurface(str(OUT / "cairo-text-only.pdf"), 595, 842)
    draw(s, pages=1, image=False)
    add("cairo-text-only.pdf", "CLEAN", ver, "single page; object streams; embedded subset font")
    # poppler's cairo backend re-rendering another document.
    run("pdftocairo", "-pdf", str(OUT / "libreoffice-docx-export.pdf"), str(OUT / "pdftocairo-rewrite.pdf"))
    add("pdftocairo-rewrite.pdf", "CLEAN", tool_version(["pdftocairo", "-v"]) + " / " + ver,
        "poppler->cairo rewrite of the LibreOffice fixture")


